"""Build manuscript tables directly from frozen research results.

Run from any directory using the standard library. Does not rerun or
modify experiments. All repeated seeds remain repeated estimates of one shot.
"""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / 'paper'
TABLES = PAPER / 'tables'
FIGURES = PAPER / 'figures'
SOURCES = [
    'report/evidence/z05-factors.csv', 'report/evidence/z06-summary.json',
    'report/evidence/z08-feedback.csv', 'experiment/runs/Z04/summary.json',
    'report/evidence/review-inference.json',
]


def csv_rows(path):
    with (ROOT / path).open(encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def write_table(name, rows):
    (TABLES / name).write_text('% Generated by paper/build_assets.py.\n' +
                              '\n'.join(' & '.join(row) + r' \\' for row in rows) + '\n',
                              encoding='utf-8', newline='\n')


def physical_marginals(evidence):
    families = evidence['parameter_marginals']
    analytic = families['analytic_checks']
    variables = [
        ('S', 'kappa_m_inv', r'\(\kappa\) (m\(^{-1}\))', 4),
        ('E', 'release_C_L', r'\(C_L\) (release)', 3),
        ('E', 'omega_norm_rad_s', 'Spin speed (rad/s)', 1),
        ('S', 'wind_speed_m_s', 'Wind speed (m/s)', 2),
        ('E', 'wind_speed_m_s', 'Wind speed (m/s)', 2),
    ]
    def interval(q, digits):
        lo, mid, hi = q
        return f'{mid:.{digits}f} [{lo:.{digits}f}, {hi:.{digits}f}]'
    rows = []
    for family, key, label, digits in variables:
        marginal = families[family]['marginals'][key]
        prior = marginal['prior_q05_q50_q95']
        prior_band = marginal['prior_mass_low_high_2pct'][1]
        post_band = marginal['posterior_mass_low_high_2pct'][1]
        if key == 'wind_speed_m_s':
            prior = analytic['uniform_disk_speed_prior_q05_q50_q95_m_s']
            prior_band = analytic['uniform_disk_speed_prior_low_high_2pct'][1]
        elif key == 'kappa_m_inv':
            prior = analytic['S_kappa_prior_q05_q50_q95']
            prior_band = 0.02
        tiny_band = 0 < prior_band < .0001
        prior_percent = f'{prior_band*100:.3f}' if tiny_band else f'{prior_band*100:.2f}'
        post_percent = f'{post_band*100:.2f}' if post_band else '0'
        rows.append([family, label, interval(prior, digits),
                     interval(marginal['posterior_q05_q50_q95'], digits),
                     f'{post_percent} / {prior_percent}'])
    return rows


def main():
    TABLES.mkdir(exist_ok=True)
    factors = {r['scenario']: r for r in csv_rows(SOURCES[0])}
    results = json.loads((ROOT / SOURCES[1]).read_text(encoding='utf-8'))['metrics']
    capture = {r['profile']: r for r in csv_rows(SOURCES[2])}
    budget = json.loads((ROOT / SOURCES[3]).read_text(encoding='utf-8'))
    factor_names = [
        ('reference', 'Nominal assumptions'),
        ('box_10mm', 'Coordinate half-width: 10 mm'),
        ('phase_plus1ms', 'Both observation times: +1 ms'),
        ('zero_wind', 'Wind cap: 0 m/s'),
        ('half_spin_beta', r'S: halve $\beta$ component limits'),
        ('half_spin_omega', r'E: halve $\omega$ component limits'),
        ('mass_410g', 'E: ball mass 410 g'),
        ('mass_450g', 'E: ball mass 450 g'),
        ('spin_model_S', 'S as the sole force model'),
        ('tracking_noise', '6 mm independent + 8 mm shared noise'),
    ]
    write_table('sensitivity.tex', [[label, f"{100*float(factors[key]['shift_from_reference_m']):.2f}",
                                    f"{float(factors[key]['region90_m2']):.3f}",
                                    f"{100*float(factors[key]['p_in']):.1f}"] for key,label in factor_names])
    write_table('equal-budget.tex', [[label, f"{budget[key]['mean_point_error_m']:.3f}",
                    f"{budget[key]['nominal90_hits']}/99", f"{budget[key]['mean_area_on_in_goal_m2']:.3f}",
                    str(budget[key]['low_ess'])] for key,label in [('late','100 ms only'),('both','50 and 100 ms')]])
    names = [('two_100ms','50, 100'),('late_pair_150ms','100, 150'),('three_150ms','50, 100, 150')]
    write_table('waiting.tex', [[label, f"{results[key]['point_error_m']['mean']:.3f}",
            str(results[key]['point_error_m']['n']), f"{results[key]['raw_hit']['hit']}/72",
            f"{results[key]['raw_area_m2']['mean']:.3f}", str(results[key]['missing_event']),
            str(results[key]['low_ess'])] for key,label in names])
    noisy = [('noisy_hard','Rounding only'),('noisy_independent','Independent error'),('noisy_shared','Shared + independent')]
    write_table('noise.tex', [[label, f"{results[key]['point_error_m']['mean']:.3f}",
            str(results[key]['point_error_m']['n']), f"{results[key]['raw_hit']['hit']}/72",
            f"{results[key]['raw_area_m2']['mean']:.3f}", f"{results[key]['cal_hit']['hit']}/72",
            f"{results[key]['cal_area_m2']['mean']:.3f}"] for key,label in noisy])
    write_table('physical-marginals.tex', physical_marginals(json.loads((ROOT / SOURCES[4]).read_bytes())))
    manifest = {s: hashlib.sha256((ROOT/s).read_bytes()).hexdigest() for s in SOURCES}
    (PAPER/'asset-sources.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps({'tables':5,'source_files':len(manifest)}))


if __name__ == '__main__':
    main()
